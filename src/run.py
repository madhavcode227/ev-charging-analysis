"""
EV charging infrastructure -- placement and viability analysis.

Run:  python3 src/run.py
"""

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))

import economics as E
import scoring as S
from data import NATIONAL, load_states

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "outputs"
OUT.mkdir(exist_ok=True)

pd.set_option("display.width", 140)


def main():
    df = load_states()
    scored = S.score(df)
    gap_rank = S.gap_only_ranking(df)

    # Does the score actually differ from the naive gap ranking?
    merged = scored.merge(gap_rank[["state", "gap_rank"]], on="state")
    merged["rank_shift"] = merged["gap_rank"] - merged["rank"]

    # ---- national gap ----
    nat_required = NATIONAL["required_2030"]
    nat_now = NATIONAL["stations_registered"]
    nat_multiple = round(nat_required / nat_now, 1)
    non_operational = nat_now - NATIONAL["stations_operational"]
    non_op_pct = round(100 * non_operational / nat_now, 1)

    # ---- economics sweep ----
    sweep = pd.DataFrame([
        E.station_economics(u) for u in [1, 2, 3, 5, 8, 10, 15, 20, 25]
    ])

    # ---- subsidy comparison at a bad site vs a good site ----
    subsidy_cmp = pd.DataFrame([
        E.station_economics(5, 0), E.station_economics(5, 20),
        E.station_economics(10, 0), E.station_economics(10, 20),
    ])

    breakeven = E.breakeven_utilization()

    # ---- console ----
    print("=" * 72)
    print("NATIONAL PICTURE")
    print("=" * 72)
    print(f"Registered stations      {nat_now:,}")
    print(f"Operational              {NATIONAL['stations_operational']:,}")
    print(f"Non-operational          {non_operational:,}  ({non_op_pct}%)")
    print(f"EVs per station          {NATIONAL['ev_charger_ratio']}"
          f"   (benchmark {NATIONAL['benchmark_ratio_low']}-"
          f"{NATIONAL['benchmark_ratio_high']})")
    print(f"Needed by 2030           {nat_required:,}  "
          f"= {nat_multiple}x today's base")

    print("\n" + "=" * 72)
    print("STATE RANKING -- placement score")
    print("=" * 72)
    cols = ["rank", "state", "score", "ev_per_charger", "gap",
            "gap_multiple", "gap_rank", "rank_shift"]
    show = merged[cols].copy()
    show["ev_per_charger"] = show["ev_per_charger"].round(0)
    print(show.to_string(index=False))

    print("\n" + "=" * 72)
    print("UNIT ECONOMICS -- one 60 kW DC station, Rs 10,00,000 capex")
    print("=" * 72)
    print(f"Break-even utilisation: {breakeven}%  "
          f"(below this it loses money every year)")
    print(sweep.to_string(index=False))

    print("\n" + "=" * 72)
    print("DOES SUBSIDY FIX A BAD SITE?")
    print("=" * 72)
    print(subsidy_cmp.to_string(index=False))

    # ---- persist ----
    merged.to_csv(OUT / "state_ranking.csv", index=False)
    sweep.to_csv(OUT / "unit_economics.csv", index=False)
    subsidy_cmp.to_csv(OUT / "subsidy_comparison.csv", index=False)

    write_report(merged, sweep, subsidy_cmp, breakeven,
                 nat_now, non_operational, non_op_pct, nat_multiple)
    make_plot(merged, sweep)


def write_report(merged, sweep, subsidy_cmp, breakeven,
                 nat_now, non_op, non_op_pct, nat_multiple):
    top5 = merged.head(5)
    biggest_shift = merged.loc[merged["rank_shift"].abs().idxmax()]

    L = []
    L.append("# EV Charging Infrastructure -- Placement and Viability\n")
    L.append("Generated by `src/run.py`. Every number below comes from a run.\n")

    L.append("\n## The question\n")
    L.append("India's charging shortfall is usually framed as a counting "
             "problem: there are 27,737 public stations and roughly 1.32 "
             "million are needed by 2030. This analysis asks a different "
             "question -- given that chargers will be built, where should "
             "they go, and what actually determines whether they pay for "
             "themselves.\n")

    L.append("\n## National picture\n")
    L.append(f"- {nat_now:,} registered public stations; {non_op:,} "
             f"({non_op_pct}%) are not operational\n")
    L.append(f"- 235 EVs per public station, against a global benchmark "
             f"band of 6-20\n")
    L.append(f"- 1.32 million stations needed by 2030 -- {nat_multiple}x "
             f"today's base\n")
    L.append("- PM E-DRIVE has allocated Rs 2,000 crore for public charging "
             "and had spent nothing as of March 2026\n")

    L.append("\n## State ranking\n")
    L.append("Score combines demand pressure (0.35), market viability "
             "(0.25), growth (0.25) and state subsidy (0.15). `gap_rank` is "
             "the naive ranking by raw shortfall; `rank_shift` is how far "
             "the score moves a state against it.\n")
    cols = ["rank", "state", "score", "ev_per_charger", "gap",
            "gap_multiple", "gap_rank", "rank_shift"]
    t = merged[cols].copy()
    t["ev_per_charger"] = t["ev_per_charger"].round(0)
    L.append(t.to_markdown(index=False))

    L.append(f"\n\nTop 5 by score: "
             f"{', '.join(top5['state'].tolist())}.\n")
    L.append(f"\nThe score and the naive gap ranking disagree most on "
             f"**{biggest_shift['state']}** "
             f"({int(abs(biggest_shift['rank_shift']))} places). That "
             f"disagreement is the model earning its keep -- if the two "
             f"rankings matched, the scoring layer would be decoration.\n")

    L.append("\n## Unit economics\n")
    L.append("One 60 kW DC fast charger. Capex Rs 10,00,000, of which the "
             "charger unit is only Rs 5,00,000 -- grid connection, civil "
             "work and land make up the other half. Margin Rs 9/kWh "
             "(Rs 18 charged, Rs 9 electricity), O&M Rs 1,00,000 a year.\n")
    L.append(f"\n**Break-even utilisation: {breakeven}%.** Below this the "
             f"station loses money every year regardless of how long it "
             f"runs.\n\n")
    L.append(sweep.to_markdown(index=False))

    L.append("\n\n## Does subsidy fix a bad site?\n")
    L.append(subsidy_cmp.to_markdown(index=False))
    L.append("\n\nA 20% capital subsidy improves a good site and does not "
             "rescue a weak one. It shortens payback where payback already "
             "existed. This matters because current support is structured "
             "as capex support, which rewards installing a charger rather "
             "than running one.\n")

    L.append("\n## Findings\n")
    L.append("\n**1. The gap is real but it is the wrong target.** A large "
             "gap can mean a thick market that is underserved, or a thin "
             "market with almost no EVs. Ranking by gap alone cannot "
             "distinguish the two, and the second case produces stranded "
             "assets.\n")
    L.append(f"\n**2. Execution is weaker than sanctioning.** {non_op_pct}% "
             f"of registered stations are not operational, and the "
             f"PM E-DRIVE charging allocation was unspent as of March 2026. "
             f"Capital is not the binding constraint.\n")
    L.append(f"\n**3. Everything turns on utilisation.** Reported real-world "
             f"utilisation runs between 1% and 5%. At 2% a station never "
             f"pays back; at 10% it pays back in under three years with no "
             f"subsidy at all. The difference is location, not technology "
             f"and not capital cost.\n")

    L.append("\n## Recommendations\n")
    L.append("\n**1. Move support from capex to delivered energy.** A "
             "per-kWh incentive pays operators for chargers that get used, "
             "which pushes site selection toward demand instead of toward "
             "whoever can install fastest.\n")
    L.append("\n**2. Select sites by dwell time, not by geography.** "
             "Highway rest stops, metro parking, bus depots and logistics "
             "hubs concentrate demand. Residential public charging competes "
             "with home charging, which already covers most urban "
             "four-wheeler miles, so those sites are structurally "
             "underused.\n")
    L.append(f"\n**3. Repair before expanding.** Roughly {non_op:,} "
             f"installed chargers are not working. Restoring them is "
             f"cheaper per usable charger than new installation and "
             f"improves network reliability, which is what actually "
             f"constrains EV adoption.\n")

    L.append("\n## Limitations\n")
    L.append("- Published station counts disagree by up to 2x across "
             "sources, depending on whether they count stations or points "
             "and registered or operational. One series was used "
             "throughout; absolute values are less reliable than the "
             "relative ranking.\n")
    L.append("- EV registration figures are cumulative and include two- and "
             "three-wheelers, which use public DC charging far less than "
             "cars. A category-weighted count would sharpen the demand "
             "metric.\n")
    L.append("- Weights are judgment, not fitted to an outcome. Running the "
             "score at different weights would show how stable the ranking "
             "is; that sensitivity check is not in this version.\n")
    L.append("- Tariffs, land cost and utilisation vary by city; the unit "
             "economics use one national set of assumptions.\n")

    (ROOT / "REPORT.md").write_text("\n".join(L))
    print(f"\nWrote {ROOT / 'REPORT.md'}")


def make_plot(merged, sweep):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5))

    ax = axes[0]
    top = merged.head(10).iloc[::-1]
    ax.barh(top["state"], top["score"], color="tab:blue")
    ax.set_title("Placement score by state (top 10)")
    ax.set_xlabel("score")
    ax.grid(alpha=.25, axis="x")

    ax = axes[1]
    s = sweep.dropna(subset=["payback_years"])
    ax.plot(s["utilization_pct"], s["payback_years"],
            marker="o", color="tab:green")
    ax.axhline(5, color="tab:red", ls="--", lw=1, label="5-year threshold")
    ax.set_title("Payback vs utilisation\n(below break-even: never pays back)")
    ax.set_xlabel("utilisation %")
    ax.set_ylabel("payback (years)")
    ax.legend()
    ax.grid(alpha=.25)

    plt.tight_layout()
    plt.savefig(OUT / "ev_analysis.png", dpi=130)
    print(f"Wrote {OUT / 'ev_analysis.png'}")


if __name__ == "__main__":
    main()
